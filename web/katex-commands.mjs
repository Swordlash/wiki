// The commands KaTeX reads in math, with the number of arguments each
// takes in braces, for the editor's completion after a backslash in math
// (WP5.124 (e) of docs/PLAN.md; wiki-core's Wiki.Core.Math.KatexCommands,
// which this writes). KaTeX publishes no list of its commands: this reads
// its own tables (its functions, symbols, macros and environments, from
// the sources its npm package ships) through esbuild, as the bundle reads
// KaTeX, so that the list is the one of the KaTeX the pages render with.
//
//   node web/katex-commands.mjs          writes the Haskell module
//   node web/katex-commands.mjs --check  fails when the module is not what
//                                        KaTeX's tables give (web/bundle.sh
//                                        runs this, so that a KaTeX that
//                                        moves its tables fails the build)
import { build } from "esbuild";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const root = new URL("..", import.meta.url);
const target = new URL("wiki-core/src/Wiki/Core/Math/KatexCommands.hs", root);

// KaTeX's tables, from its sources (TypeScript, which esbuild reads).
const entry = `
import functions from "katex/src/functions.ts";
import { _environments } from "katex/src/defineEnvironment.ts";
import "katex/src/environments.ts";
import { _macros } from "katex/src/defineMacro.ts";
import "katex/src/macros.ts";
import symbols from "katex/src/symbols.ts";
import katex from "katex";
export const tables = { functions, environments: _environments, macros: _macros, symbols, version: katex.version };
`;
const dir = mkdtempSync(join(tmpdir(), "katex-commands-"));
let tables;
try {
  const out = join(dir, "tables.mjs");
  await build({
    stdin: { contents: entry, resolveDir: new URL(".", root).pathname, loader: "js" },
    bundle: true,
    format: "esm",
    platform: "node",
    outfile: out,
    logLevel: "error",
  });
  ({ tables } = await import(pathToFileURL(out).href));
} finally {
  rmSync(dir, { recursive: true, force: true });
}

// A command's name: a backslash and letters. Others (\@foo, \!, \,) are
// not completed after letters.
const named = (name) => /^\\[A-Za-z]+$/.test(name);
const commands = new Map();
// Functions that math may hold, with their mandatory arguments.
for (const [name, spec] of Object.entries(tables.functions)) {
  if (named(name) && spec.allowedInMath !== false) commands.set(name, spec.numArgs ?? 0);
}
// Symbols of math mode: no argument.
for (const name of Object.keys(tables.symbols.math)) {
  if (named(name) && !commands.has(name)) commands.set(name, 0);
}
// Macros: those that say their number of arguments, that; one written as
// text, the highest #n in it; any other, none.
for (const [name, body] of Object.entries(tables.macros)) {
  if (!named(name) || commands.has(name)) continue;
  if (typeof body === "object" && body !== null && typeof body.numArgs === "number") commands.set(name, body.numArgs);
  else if (typeof body === "string") commands.set(name, Math.max(0, ...[...body.matchAll(/#([1-9])/g)].map((m) => Number(m[1]))));
  else commands.set(name, 0);
}
// mhchem, which the bundle adds (web/src/islands.js): its two commands.
commands.set("\\ce", 1);
commands.set("\\pu", 1);
const environments = Object.entries(tables.environments)
  .filter(([name]) => /^[A-Za-z*]+$/.test(name))
  .map(([name, spec]) => [name, spec.numArgs ?? 0])
  .sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));

const sorted = [...commands.entries()].sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
const hs = (s) => JSON.stringify(s);
const module = `-- | The commands KaTeX ${tables.version} reads in math, and its environments,
-- each with the number of arguments it takes in braces: what the editor's
-- completion offers after a backslash in math
-- ("Wiki.Core.Markdown.Complete").
--
-- Generated by @web/katex-commands.mjs@ from KaTeX's own tables; do not
-- edit. @web/bundle.sh@ checks that it is what KaTeX's tables give, and
-- fails the build otherwise.
module Wiki.Core.Math.KatexCommands
  ( katexVersion
  , katexCommands
  , katexEnvironments
  )
where

import Protolude

-- | The version of KaTeX the lists were read from.
katexVersion :: Text
katexVersion = ${hs(tables.version)}

-- | KaTeX's commands, by name with their backslash, in order, each with
-- the number of its arguments in braces.
katexCommands :: [(Text, Int)]
katexCommands =
  [ ${sorted.map(([name, args]) => `(${hs(name)}, ${args})`).join("\n  , ")}
  ]

-- | KaTeX's environments, by name, in order, each with the number of the
-- arguments its @\\\\begin@ takes in braces.
katexEnvironments :: [(Text, Int)]
katexEnvironments =
  [ ${environments.map(([name, args]) => `(${hs(name)}, ${args})`).join("\n  , ")}
  ]
`;

if (process.argv.includes("--check")) {
  const current = readFileSync(target, "utf8");
  if (current !== module) {
    console.error("wiki-core/src/Wiki/Core/Math/KatexCommands.hs is not what KaTeX's tables give: run node web/katex-commands.mjs and look at what moved.");
    process.exit(1);
  }
} else {
  writeFileSync(target, module);
}
